//! Polyphonic audio-to-MIDI transcription: an unofficial, parity-tested Rust port of
//! Spotify's [Basic Pitch](https://github.com/spotify/basic-pitch).
//!
//! Basic Pitch is a lightweight neural network that turns a recording of any instrument
//! or voice into notes, with pitch bends. This crate runs the official
//! model and reproduces the Python post-processing exactly: given the same model outputs,
//! it returns the same notes, in the same order, with the same frames, pitch bends and
//! MIDI events.
//!
//! # Quick start
//!
//! ```
//! # #[cfg(all(feature = "tract", feature = "bundled-model", feature = "midi"))] {
//! use basic_pitch::BasicPitch;
//!
//! // Two seconds of A4 (440 Hz). Audio must be mono, at 22 050 Hz.
//! let audio: Vec<f32> = (0..44_100)
//!     .map(|i| 0.5 * (2.0 * std::f32::consts::PI * 440.0 * i as f32 / 22_050.0).sin())
//!     .collect();
//!
//! let transcriber = BasicPitch::new()?;
//! let transcription = transcriber.transcribe(&audio)?;
//!
//! assert!(transcription.notes.iter().any(|note| note.pitch == 69));
//! for note in &transcription.notes {
//!     println!("{:.3}s-{:.3}s pitch {} velocity {}", note.start_s, note.end_s, note.pitch, note.velocity());
//! }
//!
//! let midi: Vec<u8> = transcription.to_midi(&Default::default())?; // a Standard MIDI File
//! # }
//! # Ok::<(), basic_pitch::Error>(())
//! ```
//!
//! The core takes samples, not files: decode and resample your audio to mono 22 050 Hz
//! first. The `basic-pitch-rs` command-line tool, from the
//! [`basic-pitch-cli`](https://crates.io/crates/basic-pitch-cli) crate, does it for common
//! audio formats.
//! Never normalize the gain: the model output depends on the absolute level.
//!
//! # Pipeline
//!
//! [`BasicPitch`] chains the steps below, each of which is public for advanced uses
//! (streaming, custom backends, re-decoding notes with other thresholds):
//!
//! 1. [`window`]: cut the audio into overlapping 2 s windows.
//! 2. [`model`]: run the network on each window ([`model::Backend`]).
//! 3. [`window::unwrap_output`]: stitch the windows into [`Posteriorgrams`] (note,
//!    onset and contour activations, one frame every ~11.6 ms).
//! 4. [`notes`]: decode note events, with optional pitch bends.
//! 5. `midi` (feature `midi`): write a Standard MIDI File.
//!
//! # Features
//!
//! | feature         | default | description |
//! |-----------------|---------|-------------|
//! | `tract`         | yes     | Pure Rust inference with [tract](https://github.com/sonos/tract); works on `wasm32-unknown-unknown`. |
//! | `bundled-model` | yes     | Embeds `nmp.onnx` (230 kB) so [`BasicPitch::new`](struct.BasicPitch.html#method.new) needs no file. |
//! | `midi`          | yes     | MIDI export with [midly](https://docs.rs/midly). |
//! | `ort`           | no      | [ONNX Runtime](https://onnxruntime.ai) backend, about 3 times faster natively. Links an ONNX Runtime 1.31 that you provide (see below). Requires Rust 1.92. |
//! | `ort-download`  | no      | `ort`, plus a prebuilt ONNX Runtime downloaded at build time and linked statically. |
//! | `serde`         | no      | `Serialize`/`Deserialize` on the public data types. |
//!
//! The `ort` feature depends on `ort` 2.0.0-rc.14 with an exact version requirement, as
//! release candidates of `ort` are not semver-compatible with each other: an application
//! that uses `ort` itself must use that same version. The crate is re-exported as
//! `basic_pitch::ort`. Without `ort-download`, the `ort` crate looks for
//! ONNX Runtime through its usual mechanisms: the `ORT_LIB_LOCATION` environment
//! variable, or features of `ort` enabled by the application, such as `load-dynamic` or
//! `download-binaries`.
//!
//! # Parity with Python
//!
//! The port targets spotify/basic-pitch 0.4.0 (PyPI). The only difference between that
//! release and the current `main` branch is how the model output is trimmed at the end
//! of the file; both are available through [`TrimMode`], and the default follows `main`,
//! which no longer drops the last frames. The test suite checks every step against
//! fixtures generated by the Python package, on 6 recordings, 8 parameter sets and both
//! trim modes:
//!
//! - windows, unwrapped outputs and frame times: bit-identical;
//! - notes, frames, amplitudes, pitch bends and MIDI events from the same
//!   posteriorgrams: identical (1650 notes, 96 MIDI files);
//! - model outputs: within 1.3e-6 of onnxruntime with tract on native targets,
//!   bit-identical with ONNX Runtime;
//! - end to end with tract, from audio to notes: 1650 of 1650 notes identical.
//!
//! One known quirk is kept on purpose: in-tune notes get a pitch bend of +1/3 of a
//! semitone, because the model's pitch contour peaks one bin high (spotify/basic-pitch#87).
//! Set [`NoteParams::bend_offset`] to `-1` to compensate.
//!
//! # WebAssembly
//!
//! The crate builds for `wasm32-unknown-unknown` with the `tract` backend:
//!
//! ```text
//! cargo build --target wasm32-unknown-unknown --no-default-features --features tract,bundled-model
//! ```
//!
//! No extra flag is needed: on that target, the `getrandom` crate (pulled in by tract)
//! is configured to use the JavaScript backend, which `wasm-bindgen` provides. For a
//! host without JavaScript, build with
//! `RUSTFLAGS='--cfg getrandom_backend="unsupported"'` instead; the model never asks for
//! random numbers. Add `-C target-feature=+simd128` to `RUSTFLAGS` for tract's SIMD
//! kernels, about 2.4 times faster.
//!
//! The repository's `examples/wasm` has `wasm-bindgen` bindings, a browser demo and a
//! parity check that runs in Node and in browsers. tract's WebAssembly kernels do not use
//! fused multiply-add, so the model outputs differ from Python by up to about 5e-4 instead
//! of 1e-6. On the parity fixtures, the notes stay the same except for one pitch bend
//! frame in 825 notes, and amplitudes move by less than 1e-4.
//!
//! # Threads
//!
//! The model runs on one 2 s window at a time, and the windows are independent.
//! [`BasicPitch::with_threads`] spreads them over several threads with identical results,
//! which speeds up long files with tract. The ONNX Runtime backend already uses every
//! core for each window.
//!
//! # Stability
//!
//! The crate follows semantic versioning; before 1.0, breaking changes bump the minor
//! version. Parameter and note structs have public fields, so adding a field to them is
//! a breaking change, released in a new minor version. The `midi` module re-exports
//! [`midly`](https://docs.rs/midly) 0.5, whose types appear in its API.
//!
